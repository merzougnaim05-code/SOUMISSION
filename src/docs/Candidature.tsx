const COLS = '11.735% 13.927% 11.735% 17.215% 24.26% 9.391% 11.735%';
const GRAY = '#d9d9d9';
const FONT = 'Arial, "Segoe UI", Tahoma, sans-serif';

type Align = 'right' | 'left' | 'center';

function Row({h, children}: {h: number; children?: ReactNode}) {
  return (
    <div
      style={{
        display: 'grid',
        gridTemplateColumns: COLS,
        height: `${h}pt`,
        width: '100%',
        alignItems: 'stretch',
      }}
    >
      {children}
    </div>
  );
}

function Band({c, h}: {c: string; h?: number}) {
  return <div style={{gridColumn: c, gridRow: 1, background: GRAY, height: h ? `${h}pt` : 'auto'}} />;
}

function T({
  c,
  children,
  al = 'right',
  bold,
  size = 11,
}: {
  c: string;
  children: ReactNode;
  al?: Align;
  bold?: boolean;
  size?: number;
}) {
  return (
    <div
      style={{
        gridColumn: c,
        gridRow: 1,
        zIndex: 2,
        display: 'flex',
        alignItems: 'flex-end',
        justifyContent: al === 'left' ? 'flex-end' : al === 'center' ? 'center' : 'flex-start',
        fontSize: `${size}pt`,
        fontWeight: bold ? 700 : 400,
        whiteSpace: 'pre',
        lineHeight: 1.25,
        overflow: 'visible',
      }}
    >
      <span>{children}</span>
    </div>
  );
}

